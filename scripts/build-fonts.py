#!/usr/bin/env python3
"""Builds the icon font the app bundles: only the Phosphor icons listed in ICONS, cut from
egui-phosphor's Phosphor.ttf (regular), and `src/ui/icon_codes.rs` with their code points.

Needs fontTools (`python3 -m venv /tmp/ft && /tmp/ft/bin/pip install fonttools`, then run this
script with `/tmp/ft/bin/python3 scripts/build-fonts.py`) and the egui-phosphor crate in the
cargo registry (`cargo fetch` brings it: it is a dependency's source only, not linked).

Add an icon: put its name (as egui-phosphor spells it) in ICONS and rerun.
"""

import glob
import os
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ICONS = """
ARROWS_CLOCKWISE ARROW_CIRCLE_UP ARROW_DOWN ARROW_LEFT ARROW_RIGHT ARROW_SQUARE_OUT ARROW_UP BELL
CARET_DOWN CARET_RIGHT CARET_UP CHECK_CIRCLE CIRCLE CIRCLE_HALF CIRCLE_NOTCH
CLOCK_COUNTER_CLOCKWISE CODE COMMAND DOWNLOAD_SIMPLE FILE FILES FILE_CODE FILE_CSV FILE_DOC
FILE_IMAGE FILE_MD FILE_PDF FILE_PPT FILE_TEXT FILE_XLS FILE_ZIP FLOPPY_DISK FOLDER FOLDER_OPEN
FOLDER_PLUS GEAR GEAR_SIX GIT_BRANCH IMAGE INFO KEYBOARD LIGHTNING LINK_SIMPLE LIST
MAGNIFYING_GLASS MAGNIFYING_GLASS_MINUS MAGNIFYING_GLASS_PLUS PACKAGE PENCIL_SIMPLE PLAY PLUG
PLUGS_CONNECTED PLUS SIDEBAR_SIMPLE SIGN_OUT SQUARE_SPLIT_HORIZONTAL SQUARE_SPLIT_VERTICAL STOP
TABLE TERMINAL TERMINAL_WINDOW TEXT_AA TRANSLATE TRASH USER WARNING X X_CIRCLE
CHECK TRAY SQUARES_FOUR GIT_DIFF SPARKLE FUNNEL PAINT_BRUSH PALETTE COLUMNS COPY CLIPBOARD_TEXT
SELECTION BROOM ARROWS_OUT_SIMPLE ARROW_U_UP_LEFT ARROW_LINE_DOWN CLOCK_COUNTER_CLOCKWISE EYE
""".split()

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_FONT = os.path.join(ROOT, "crates/tc-term/assets/fonts/Phosphor.ttf")
OUT_CODES = os.path.join(ROOT, "src/ui/icon_codes.rs")


def phosphor_dir():
    found = []
    for d in glob.glob(os.path.expanduser("~/.cargo/registry/src/*/egui-phosphor-*/")):
        name = os.path.basename(os.path.normpath(d))
        m = re.fullmatch(r"egui-phosphor-(\d+)\.(\d+)\.(\d+)(-[^+]+)?(\+.*)?", name)
        if m:
            # The newest by version, not by name (0.10.0 comes after 0.9.0), a release after its
            # pre-releases.
            version = (int(m[1]), int(m[2]), int(m[3]), m[4] is None, m[4] or "")
            found.append((version, d))
    if not found:
        sys.exit("egui-phosphor is not in the cargo registry (run `cargo fetch` in a project using it)")
    return max(found)[1]


def main():
    src = phosphor_dir()
    codes = {}
    with open(os.path.join(src, "src/variants/codepoints.rs"), encoding="utf-8") as f:
        for m in re.finditer(r'pub const (\w+): &str = "\\u\{([0-9A-Fa-f]+)\}"', f.read()):
            codes[m.group(1)] = int(m.group(2), 16)
    missing = [n for n in ICONS if n not in codes]
    if missing:
        sys.exit("not in Phosphor: " + ", ".join(missing))
    names = sorted(set(ICONS))

    font = TTFont(os.path.join(src, "res/Phosphor.ttf"))
    opts = subset.Options()
    opts.layout_features = []
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=[codes[n] for n in names])
    sub.subset(font)
    font.save(OUT_FONT)

    with open(OUT_CODES, "w", encoding="utf-8") as f:
        f.write("//! Code points of the bundled Phosphor icon subset (generated by\n")
        f.write("//! `scripts/build-fonts.py`; add names there and rerun it). Use them through `icons`.\n\n")
        f.write("#![allow(dead_code)]\n\n")
        for n in names:
            f.write(f'pub const {n}: &str = "\\u{{{codes[n]:04X}}}";\n')
    print(f"{len(names)} icons, {os.path.getsize(OUT_FONT)} bytes")


if __name__ == "__main__":
    main()
